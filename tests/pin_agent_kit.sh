#!/usr/bin/env bash
# scripts/pin-agent-kit against local remotes: a fake agent-kit, a fake bootstrap origin, and a gh
# stub that records its calls. No network and no push beyond the fake origin.
set -euo pipefail
repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
fail() { printf 'FAIL %s\n' "$1" >&2; exit 1; }
export GIT_CONFIG_NOSYSTEM=1 GIT_CONFIG_GLOBAL=/dev/null GIT_AUTHOR_NAME=test GIT_AUTHOR_EMAIL=test@example.invalid
export GIT_COMMITTER_NAME=test GIT_COMMITTER_EMAIL=test@example.invalid HOME="$work/home"
mkdir -p "$HOME"

# agent-kit: main has an old and a new role; a side branch holds a commit main never reaches.
kit="$work/agent-kit"
git init --quiet --initial-branch=main "$kit"
mkdir -p "$kit/claude/agents"
role_text() {
    printf -- '---\nname: autopilot-owner\nmodel: claude-opus-5-5\n---\n\n%s Report code-ready, and escalate anything outside the brief in your report.\n' "$1"
}
role_text 'Old charter.' >"$kit/claude/agents/autopilot-owner.md"
git -C "$kit" add -A && git -C "$kit" commit --quiet -m 'Old charter (#1)'
old="$(git -C "$kit" rev-parse HEAD)"
role_text 'New charter.' >"$kit/claude/agents/autopilot-owner.md"
git -C "$kit" commit --quiet -am 'New charter (#2)'
new="$(git -C "$kit" rev-parse HEAD)"
git -C "$kit" checkout --quiet -b side
git -C "$kit" commit --quiet --allow-empty -m 'Unmerged'
side="$(git -C "$kit" rev-parse HEAD)"
git -C "$kit" checkout --quiet main

# bootstrap: the scripts under test, a catalog pinning the old commit, the Pi role, and a stub
# validate that records where it ran and fails on request.
seed="$work/seed"
mkdir -p "$seed/scripts" "$seed/pi/agents"
cp "$repo/scripts/pin" "$repo/scripts/pin-agent-kit" "$repo/scripts/check-agent-kit-role" "$seed/scripts/"
printf '#!/usr/bin/env bash\nset -eu\npwd >>"$PIN_TEST_VALIDATED"\nscripts/check-agent-kit-role\n[ ! -e "$PIN_TEST_VALIDATED.fail" ]\n' >"$seed/scripts/validate"
chmod +x "$seed/scripts/validate"
printf '# catalog\n#name\tgroups\tversion\tplatform\tsha256\tsource\tbins\nagent-kit\tinternal\t%s\tany\t-\tgit:%s\t-\n' "$old" "$kit" >"$seed/catalog.tsv"
marker() { printf '# Body generated by scripts/pin-agent-kit from agent-kit %s claude/agents/autopilot-owner.md; change it there, not here.' "$1"; }
printf -- '---\nname: autopilot-owner\ntools: read, contact_supervisor\n%s\n---\n\nOld charter. Report code-ready, and escalate anything outside the brief through the supervisor.\n' "$(marker "$old")" >"$seed/pi/agents/autopilot-owner.md"
git init --quiet --initial-branch=main "$seed"
git -C "$seed" add -A && git -C "$seed" commit --quiet -m 'Seed'
git clone --quiet --bare "$seed" "$work/origin.git"
checkout="$work/checkout"
git clone --quiet "$work/origin.git" "$checkout"
script="$checkout/scripts/pin-agent-kit"
export PIN_TEST_VALIDATED="$work/validated"

# gh stub: `pr list` keeps only the fields the script asks for with --json, as gh does, and applies
# its --jq filter (with jq) to $work/open-prs.json, the open pull requests; `pr create` saves its
# body and prints a URL.
printf '[]\n' >"$work/open-prs.json"
# One pull request in the shape gh 2.102.0 (catalog.tsv's pin) returns, captured from
# `gh pr list -R elijah-rou/bootstrap --state all --limit 2 --json number,headRefName,isCrossRepository,headRepositoryOwner,headRepository`.
open_pr_json() { # BRANCH URL CROSS_REPOSITORY HEAD_OWNER
    printf '{"headRefName": "%s", "url": "%s", "isCrossRepository": %s, "headRepository": {"id": "R_kgDOUQdX2w", "name": "bootstrap", "nameWithOwner": "%s/bootstrap"}, "headRepositoryOwner": {"id": "MDQ6VXNlcjE1MTI3NzM1", "name": "Owner Name", "login": "%s"}, "number": 5}' "$1" "$2" "$3" "$4" "$4"
}
# gh before 2.89 (cli/cli 5ed8cf0) queried headRepository{id,name}: no nameWithOwner.
older_gh_pr_json() { # BRANCH URL CROSS_REPOSITORY HEAD_OWNER
    open_pr_json "$@" | jq -c 'del(.headRepository.nameWithOwner)'
}
mkdir -p "$work/bin"
cat >"$work/bin/gh" <<STUB
#!/usr/bin/env bash
printf '%s\n' "\$*" >>"$work/gh.log"
case "\$1 \$2" in
    'pr list')
        while [[ \$# -gt 0 ]]; do
            [[ "\$1" == --json ]] && fields="\$2"
            [[ "\$1" == --jq ]] && filter="\$2"
            shift
        done
        jq -c "map({\$fields})" "$work/open-prs.json" | jq -r "\$filter" ;;
    'pr create')
        while [[ \$# -gt 0 ]]; do [[ "\$1" == --body-file ]] && cp "\$2" "$work/pr-body.md"; shift; done
        printf 'Creating pull request\nhttps://github.invalid/bootstrap/pull/7\n' ;;
    *) exit 1 ;;
esac
STUB
chmod +x "$work/bin/gh"
export PATH="$work/bin:$PATH"
branch="agent/pin-agent-kit-${new:0:12}"
remote_branch() { git -C "$work/origin.git" rev-parse --verify --quiet "refs/heads/$1" || true; }
# The PR body's line for the Pi role pinned at commit $1: regenerated, with its diff left to the reviewer.
role_line() { printf -- "- \`pi/agents/autopilot-owner.md\`: regenerated from agent-kit's \`claude/agents/autopilot-owner.md\` at %s, with the Pi escalation line" "${1:0:12}"; }
worktrees() { git -C "$checkout" worktree list --porcelain | grep -c '^worktree '; }

# Usage errors and commits main does not reach: exit 2, nothing pushed, no GitHub call.
for argument in abc "${new:0:12}" "${new}0" --bogus; do
    status=0; "$script" "$argument" >/dev/null 2>&1 || status=$?
    [[ "$status" == 2 ]] || fail "argument $argument exited $status, not 2"
done
for argument in "$side" 0123456789012345678901234567890123456789; do
    status=0; "$script" "$argument" >/dev/null 2>"$work/err" || status=$?
    [[ "$status" == 2 ]] || fail "unreachable $argument exited $status, not 2"
    grep -q 'not a commit reachable' "$work/err" || fail "unreachable $argument: $(cat "$work/err")"
done
status=0; "$script" "$new" extra >/dev/null 2>&1 || status=$?
[[ "$status" == 2 ]] || fail "two commits exited $status, not 2"

# scripts/pin would move the catalog row without the Pi role, so it refuses agent-kit and names the
# script that moves both.
status=0; "$checkout/scripts/pin" agent-kit "$new" >/dev/null 2>"$work/err" || status=$?
[[ "$status" == 1 ]] && grep -qF 'scripts/pin-agent-kit' "$work/err" || fail "scripts/pin agent-kit: $status $(cat "$work/err")"
[[ -z "$(git -C "$checkout" status --porcelain)" ]] || fail 'scripts/pin agent-kit changed the checkout'

# The Pi role's marker must name the catalog's pin: a pin moved by hand fails the check.
"$checkout/scripts/check-agent-kit-role" || fail 'check-agent-kit-role failed on the seed'
sed -i.bak "s/$old/$new/" "$checkout/catalog.tsv" && rm "$checkout/catalog.tsv.bak"
status=0; "$checkout/scripts/check-agent-kit-role" 2>"$work/err" || status=$?
[[ "$status" == 1 ]] && grep -qF 'move both with scripts/pin-agent-kit' "$work/err" || fail "hand pin: $status $(cat "$work/err")"
git -C "$checkout" checkout --quiet -- catalog.tsv

# The pinned commit is current: exit 0, no branch, no GitHub call.
output="$("$script" "$old")" || fail 'current pin exited nonzero'
[[ "$output" == "agent-kit pin is current: origin/main pins $old" ]] || fail "current pin printed: $output"
output="$("$script" "$(tr a-f A-F <<<"$old")")" || fail 'uppercase current pin exited nonzero'
[[ "$output" == "agent-kit pin is current: origin/main pins $old" ]] || fail "uppercase current pin printed: $output"
[[ ! -e "$work/gh.log" ]] || fail 'current pin called gh'

# Dry run: the diff summary, validate in a temporary worktree, then no commit, push, or worktree.
output="$("$script" --dry-run)" || fail 'dry run exited nonzero'
[[ "$output" == *'catalog.tsv'* && "$output" == *'pi/agents/autopilot-owner.md'* ]] || fail "dry run summary: $output"
[[ "$output" == *"Dry run: would commit \"Pin agent-kit ${new:0:12}\""* ]] || fail "dry run tail: $output"
[[ -s "$PIN_TEST_VALIDATED" ]] || fail 'dry run did not validate'
[[ "$(cat "$PIN_TEST_VALIDATED")" != "$checkout" ]] || fail 'validate ran in the checkout, not a worktree'
[[ -z "$(remote_branch "$branch")" ]] || fail 'dry run pushed'
[[ ! -e "$work/gh.log" ]] || fail 'dry run called gh'
[[ "$(worktrees)" == 1 ]] || fail 'dry run left a worktree'
[[ -z "$(git -C "$checkout" status --porcelain)" ]] || fail 'dry run changed the checkout'

# A failing validate stops before the commit.
touch "$PIN_TEST_VALIDATED.fail"
status=0; "$script" >/dev/null 2>"$work/err" || status=$?
[[ "$status" == 1 ]] || fail "failing validate exited $status"
grep -q 'nothing was committed or pushed' "$work/err" || fail "failing validate: $(cat "$work/err")"
[[ -z "$(remote_branch "$branch")" ]] || fail 'failing validate pushed'
[[ "$(worktrees)" == 1 ]] || fail 'failing validate left a worktree'
rm "$PIN_TEST_VALIDATED.fail"

# Another open pin pull request from this repository would conflict with this one on the agent-kit
# row: refuse, name it, and change nothing, in the shape current gh returns and the older one.
for shape in open_pr_json older_gh_pr_json; do
    printf '[%s]\n' "$("$shape" agent/pin-agent-kit-0123456789ab https://github.invalid/bootstrap/pull/5 false elijah-rou)" >"$work/open-prs.json"
    : >"$work/gh.log"
    status=0; "$script" >/dev/null 2>"$work/err" || status=$?
    [[ "$status" == 1 ]] || fail "other open pin ($shape) exited $status"
    grep -qF 'https://github.invalid/bootstrap/pull/5' "$work/err" || fail "other open pin ($shape): $(cat "$work/err")"
    [[ -z "$(remote_branch "$branch")" ]] || fail "other open pin ($shape) pushed"
    ! grep -q '^pr create' "$work/gh.log" || fail "other open pin ($shape) opened a pull request"
    [[ "$(worktrees)" == 1 ]] || fail "other open pin ($shape) left a worktree"
done

# The real run with no argument pins agent-kit's main. A fork's pull request on the same branch
# name is not this repository's pin, and neither is a branch that only shares the prefix.
: >"$work/gh.log"
printf '[%s, %s]\n' "$(open_pr_json "$branch" https://github.invalid/bootstrap/pull/6 true someone)" \
    "$(open_pr_json agent/pin-agent-kit-script https://github.invalid/bootstrap/pull/4 false elijah-rou)" >"$work/open-prs.json"
output="$("$script")" || fail 'pin exited nonzero'
[[ "${output##*$'\n'}" == https://github.invalid/bootstrap/pull/7 ]] || fail "last line is not the URL: $output"
grep -q '^pr list .*--repo elijah-rou/bootstrap' "$work/gh.log" || fail "gh pr list: $(cat "$work/gh.log")"
head="$(remote_branch "$branch")"
[[ -n "$head" ]] || fail "no $branch on origin"
[[ "$(git -C "$work/origin.git" log -1 --format=%s "$head")" == "Pin agent-kit ${new:0:12}" ]] || fail 'commit subject'
[[ "$(git -C "$work/origin.git" rev-parse "$head^")" == "$(git -C "$work/origin.git" rev-parse main)" ]] || fail 'not one commit on origin/main'
[[ "$(git -C "$work/origin.git" diff --name-only "$head^" "$head" | tr '\n' ' ')" == 'catalog.tsv pi/agents/autopilot-owner.md ' ]] || fail 'changed files'
git -C "$work/origin.git" show "$head:catalog.tsv" | grep -q "^agent-kit	internal	$new	" || fail 'catalog does not pin the new commit'
expected="$(printf -- '---\nname: autopilot-owner\ntools: read, contact_supervisor\n%s\n---\n\nNew charter. Report code-ready, and escalate anything outside the brief through the supervisor.' "$(marker "$new")")"
[[ "$(git -C "$work/origin.git" show "$head:pi/agents/autopilot-owner.md")" == "$expected" ]] || fail 'Pi role not synced'
grep -q -- "--head $branch --title Pin agent-kit ${new:0:12}" "$work/gh.log" || fail "gh pr create: $(cat "$work/gh.log")"
for section in '## Why' '## What changed' '## Verification' '## Revert' "elijah-rou/agent-kit@${new:0:7} New charter (elijah-rou/agent-kit#2)" "$(role_line "$new")"; do
    grep -qF -- "$section" "$work/pr-body.md" || fail "PR body lacks $section"
done
# agent-kit's issue numbers would resolve against bootstrap in this repository's pull request.
! grep -qE '(^|[^/[:alnum:]])#[0-9]' "$work/pr-body.md" || fail "PR body has an unqualified issue reference: $(cat "$work/pr-body.md")"
! grep -q 'merge' "$work/gh.log" || fail 'pin called gh pr merge'
[[ "$(worktrees)" == 1 ]] || fail 'pin left a worktree'
[[ -z "$(git -C "$checkout" branch --list 'agent/*')" ]] || fail 'pin left a local branch'

# An open pull request on the branch from this repository is reused: its URL, no push, no new one.
for shape in open_pr_json older_gh_pr_json; do
    printf '[%s]\n' "$("$shape" "$branch" https://github.invalid/bootstrap/pull/7 false elijah-rou)" >"$work/open-prs.json"
    : >"$work/gh.log"
    output="$("$script" "$new")" || fail "reuse ($shape) exited nonzero"
    [[ "${output##*$'\n'}" == https://github.invalid/bootstrap/pull/7 ]] || fail "reuse ($shape) printed: $output"
    [[ "$(remote_branch "$branch")" == "$head" ]] || fail "reuse ($shape) pushed"
    ! grep -q '^pr create' "$work/gh.log" || fail "reuse ($shape) opened another pull request"
done
printf '[]\n' >"$work/open-prs.json"

# A pushed branch with no open pull request: validate it and open the pull request, never rewrite it.
: >"$work/gh.log" && : >"$PIN_TEST_VALIDATED"
output="$("$script")" || fail 'resume exited nonzero'
[[ "${output##*$'\n'}" == https://github.invalid/bootstrap/pull/7 ]] || fail "resume printed: $output"
[[ "$(remote_branch "$branch")" == "$head" ]] || fail 'resume rewrote the branch'
grep -q '^pr create' "$work/gh.log" || fail 'resume did not open the pull request'
[[ -s "$PIN_TEST_VALIDATED" ]] || fail 'resume did not validate the pushed branch'
grep -qF -- "$(role_line "$new")" "$work/pr-body.md" || fail "resume body lacks the role line: $(cat "$work/pr-body.md")"

# A branch of that name that pins something else is left alone.
git -C "$work/origin.git" update-ref "refs/heads/$branch" main
status=0; "$script" >/dev/null 2>"$work/err" || status=$?
[[ "$status" == 1 ]] && grep -q 'does not pin' "$work/err" || fail "foreign branch: $status $(cat "$work/err")"
git -C "$work/origin.git" update-ref -d "refs/heads/$branch"

# Once origin/main pins agent-kit's main, a run with no argument is current.
git -C "$work/origin.git" update-ref refs/heads/main "$head"
output="$("$script")" || fail 'current main exited nonzero'
[[ "$output" == "agent-kit pin is current: origin/main pins $new" ]] || fail "current main printed: $output"
output="$("$script" "$old")" || fail 'older commit exited nonzero'
[[ "$output" == "agent-kit pin is current: origin/main pins $new, which contains $old" ]] || fail "older commit printed: $output"
[[ "$(worktrees)" == 1 ]] || fail 'older commit left a worktree'

# An agent-kit commit that leaves the role alone moves only the marker line. The body still names the
# role as regenerated and leaves the diff to the reviewer, on the fresh path and on the resume path.
git -C "$kit" commit --quiet --allow-empty -m 'Unrelated'
same="$(git -C "$kit" rev-parse HEAD)"
: >"$work/gh.log"
"$script" >/dev/null || fail 'marker-only pin exited nonzero'
same_head="$(remote_branch "agent/pin-agent-kit-${same:0:12}")"
[[ -n "$same_head" ]] || fail 'marker-only pin pushed no branch'
[[ "$(git -C "$work/origin.git" diff "$same_head^" "$same_head" -- pi/agents/autopilot-owner.md | grep -c '^[-+][^-+]')" == 2 ]] ||
    fail "marker-only pin changed more than the marker: $(git -C "$work/origin.git" diff "$same_head^" "$same_head")"
for path in fresh resume; do
    grep -qF -- "$(role_line "$same")" "$work/pr-body.md" && ! grep -qE 'already matches|body synced' "$work/pr-body.md" ||
        fail "marker-only pin ($path) body: $(cat "$work/pr-body.md")"
    rm "$work/pr-body.md"
    [[ "$path" == resume ]] || "$script" >/dev/null || fail 'marker-only resume exited nonzero'
done
[[ "$(remote_branch "agent/pin-agent-kit-${same:0:12}")" == "$same_head" ]] || fail 'marker-only resume rewrote the branch'

# Text added to the Pi body by hand would be erased by the next pin: stop and name it instead.
git clone --quiet "$work/origin.git" "$work/edit"
printf 'Ask through contact_supervisor before rebasing.\n' >>"$work/edit/pi/agents/autopilot-owner.md"
git -C "$work/edit" commit --quiet -am 'Pi-only text' && git -C "$work/edit" push --quiet origin HEAD:main
status=0; "$script" --dry-run >/dev/null 2>"$work/err" || status=$?
[[ "$status" == 1 ]] && grep -qF 'differs from agent-kit' "$work/err" || fail "hand-edited role: $status $(cat "$work/err")"
[[ "$(worktrees)" == 1 ]] || fail 'hand-edited role left a worktree'
git -C "$work/origin.git" update-ref refs/heads/main "$head"

# An agent-kit role without the escalation line stops the run instead of dropping the Pi wording.
printf -- '---\nname: autopilot-owner\n---\n\nReworded.\n' >"$kit/claude/agents/autopilot-owner.md"
git -C "$kit" commit --quiet -am 'Reword'
status=0; "$script" --dry-run >/dev/null 2>"$work/err" || status=$?
[[ "$status" == 1 ]] && grep -q 'update the Pi substitution' "$work/err" || fail "reworded role: $status $(cat "$work/err")"
[[ "$(worktrees)" == 1 ]] || fail 'reworded role left a worktree'

printf 'PASS pin-agent-kit\n'
